// Writes src/audio/gapDialogue.ts from src/audio/gapScript.json, spacing the lines by their REAL voice
// lengths (src/audio/gapTimings.json). With --estimate (before voices exist) every line gets a roomy 4 s slot.
//   node scripts/layout-gap.mjs --estimate     # before generating voices
//   node scripts/layout-gap.mjs                # after voices + timings: tight timeline
import {existsSync, readFileSync, writeFileSync} from 'node:fs';
import {dirname, join} from 'node:path';
import {fileURLToPath} from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const spec = JSON.parse(readFileSync(join(root, 'src/audio/gapScript.json'), 'utf8'));
const estimate = process.argv.includes('--estimate');
const timingsPath = join(root, 'src/audio/gapTimings.json');
const timings = !estimate && existsSync(timingsPath) ? JSON.parse(readFileSync(timingsPath, 'utf8')) : {};

let t = 0;
const rows = spec.lines.map((l) => {
  t += l.pause;
  const len = estimate ? 120 : (timings[l.id]?.durationFrames ?? 120);
  const from = t;
  const to = from + len + 2;
  t = to;
  return {...l, from, to};
});
const total = t + spec.tail;
const q = (s) => JSON.stringify(s);
const out = `// GENERATED by scripts/layout-gap.mjs from src/audio/gapScript.json - edit the script there, not here.
// "The Gap" v2 dialogue at 30fps. Voices: public/assets/audio/gap/voiceover/<id>.mp3

export type GapCharacter = 'brain' | 'mo' | 'heart' | 'lungs' | 'gums' | 'tongue' | 'lefty' | 'righty' | 'upper' | 'bone';

export type GapLine = {
  id: string;
  character: GapCharacter;
  text: string;
  fromFrame: number;
  toFrame: number;
  voiceFile: string;
  delay?: number;
};

export const GAP_TOTAL_FRAMES = ${total};

export const gapDialogue: GapLine[] = [
${rows.map((r) => `  {id: '${r.id}', character: '${r.character}', text: ${q(r.text)}, fromFrame: ${r.from}, toFrame: ${r.to}, voiceFile: 'assets/audio/gap/voiceover/${r.id}.mp3'},`).join('\n')}
];

/** Frame helpers for the scene: start / end of a line. */
export const L = (id: string) => {
  const l = gapDialogue.find((x) => x.id === id);
  if (!l) throw new Error('no line ' + id);
  return {from: l.fromFrame, to: l.toFrame};
};
`;
writeFileSync(join(root, 'src/audio/gapDialogue.ts'), out);
console.log(`gapDialogue.ts: ${rows.length} lines, ${total} frames (${(total / 30).toFixed(1)} s)${estimate ? ' [estimate]' : ''}`);
