// Generic: writes a dialogue .ts from a script .json, spacing lines by their REAL voice lengths.
//   node scripts/layout-dialogue.mjs SPEC.json OUT.ts TIMINGS.json VOICE_DIR [--estimate]
import {existsSync, readFileSync, writeFileSync} from 'node:fs';
const [spec, out, timingsPath, voiceDir] = process.argv.slice(2);
const estimate = process.argv.includes('--estimate');
const S = JSON.parse(readFileSync(spec, 'utf8'));
const T = !estimate && existsSync(timingsPath) ? JSON.parse(readFileSync(timingsPath, 'utf8')) : {};
let t = 0;
const rows = S.lines.map((l) => {
  t += l.pause;
  const len = estimate ? 120 : (T[l.id]?.durationFrames ?? 120);
  const r = {...l, from: t, to: t + len + 2};
  t = r.to;
  return r;
});
const total = t + S.tail;
writeFileSync(
  out,
  `// GENERATED by scripts/layout-dialogue.mjs from ${spec} - edit the script there, not here.
export type Line = {id: string; character: string; text: string; fromFrame: number; toFrame: number; voiceFile: string; delay?: number};
export const TOTAL_FRAMES = ${total};
export const dialogue: Line[] = [
${rows.map((r) => `  {id: '${r.id}', character: '${r.character}', text: ${JSON.stringify(r.text)}, fromFrame: ${r.from}, toFrame: ${r.to}, voiceFile: '${voiceDir}/${r.id}.mp3'},`).join('\n')}
];
export const L = (id: string) => {
  const l = dialogue.find((x) => x.id === id);
  if (!l) throw new Error('no line ' + id);
  return {from: l.fromFrame, to: l.toFrame};
};
`,
);
console.log(`${out}: ${rows.length} lines, ${total} frames (${(total / 30).toFixed(1)} s)${estimate ? ' [estimate]' : ''}`);
